// Generates lib/welcome-path.ts: the "Welcome" handwriting as SVG outline contours, ordered
// left to right, with per-stroke timings for the intro animation.
//
// Run with: pnpm --filter ui-shell generate:welcome-path
//
// opentype.js and @fontsource/sacramento are devDependencies used only by this script. The
// runtime bundle imports only the generated lib/welcome-path.ts.
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import opentype from 'opentype.js'

const require = createRequire(import.meta.url)
const here = dirname(fileURLToPath(import.meta.url))
const outFile = join(here, '..', 'lib', 'welcome-path.ts')

const FONT_PKG = '@fontsource/sacramento'
const fontPkgDir = dirname(require.resolve(`${FONT_PKG}/package.json`))
const fontPkg = JSON.parse(readFileSync(join(fontPkgDir, 'package.json'), 'utf8'))
const fontFile = join(fontPkgDir, 'files', 'sacramento-latin-400-normal.woff')

const TEXT = 'Welcome'
const FONT_SIZE = 220
const BASELINE = 220
const START_MS = 200
const WINDOW_MS = 2600
const SEGMENTS = 64
const PAD = 16 // room for the drawing stroke; keeps the box near the specified ~640x190 proportion

const buf = readFileSync(fontFile)
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength))
const path = font.getPath(TEXT, 0, BASELINE, FONT_SIZE)

// Split into contours: one per M command.
const contours = []
for (const cmd of path.commands) {
  if (cmd.type === 'M') contours.push([])
  contours[contours.length - 1].push(cmd)
}

function bezierPoint(p0, p1, p2, p3, t) {
  const u = 1 - t
  return u * u * u * p0 + 3 * u * u * t * p1 + 3 * u * t * t * p2 + t * t * t * p3
}

function measure(cmds) {
  let len = 0
  let minX = Infinity
  let x = 0, y = 0, sx = 0, sy = 0
  const seg = (nx, ny) => { len += Math.hypot(nx - x, ny - y); x = nx; y = ny; minX = Math.min(minX, nx) }
  for (const c of cmds) {
    if (c.type === 'M') { x = sx = c.x; y = sy = c.y; minX = Math.min(minX, c.x) }
    else if (c.type === 'L') seg(c.x, c.y)
    else if (c.type === 'Q' || c.type === 'C') {
      const x0 = x, y0 = y
      // Promote quadratic to cubic.
      const [x1, y1, x2, y2] = c.type === 'Q'
        ? [x0 + (2 / 3) * (c.x1 - x0), y0 + (2 / 3) * (c.y1 - y0), c.x + (2 / 3) * (c.x1 - c.x), c.y + (2 / 3) * (c.y1 - c.y)]
        : [c.x1, c.y1, c.x2, c.y2]
      for (let i = 1; i <= SEGMENTS; i++) {
        const t = i / SEGMENTS
        seg(bezierPoint(x0, x1, x2, c.x, t), bezierPoint(y0, y1, y2, c.y, t))
      }
    } else if (c.type === 'Z') seg(sx, sy)
  }
  return { len, minX }
}

// cubic-bezier(0.45, 0, 0.25, 1). A CSS easing maps time x(u) -> progress y(u). The reveal
// must follow it, so for a cumulative length fraction (progress) we solve y(u) = progress and
// return the normalised time x(u).
function timeForProgress(progress) {
  const P1x = 0.45, P1y = 0, P2x = 0.25, P2y = 1
  const by = u => bezierPoint(0, P1y, P2y, 1, u)
  let lo = 0, hi = 1
  for (let i = 0; i < 60; i++) {
    const mid = (lo + hi) / 2
    if (by(mid) < progress) lo = mid; else hi = mid
  }
  return bezierPoint(0, P1x, P2x, 1, (lo + hi) / 2)
}

const r = n => Math.round(n * 10) / 10
const fmt = n => String(r(n) === 0 ? 0 : r(n))

function toD(cmds) {
  return cmds.map(c => {
    switch (c.type) {
      case 'M': case 'L': return `${c.type}${fmt(c.x)} ${fmt(c.y)}`
      case 'Q': return `Q${fmt(c.x1)} ${fmt(c.y1)} ${fmt(c.x)} ${fmt(c.y)}`
      case 'C': return `C${fmt(c.x1)} ${fmt(c.y1)} ${fmt(c.x2)} ${fmt(c.y2)} ${fmt(c.x)} ${fmt(c.y)}`
      case 'Z': return 'Z'
      default: throw new Error(`unexpected command ${c.type}`)
    }
  }).join('')
}

const measured = contours
  .map(cmds => ({ cmds, ...measure(cmds) }))
  .filter(c => c.len > 0)
  .sort((a, b) => a.minX - b.minX)

const total = measured.reduce((s, c) => s + c.len, 0)
let acc = 0
const strokes = measured.map(c => {
  const t0 = START_MS + WINDOW_MS * timeForProgress(acc / total)
  acc += c.len
  const t1 = START_MS + WINDOW_MS * timeForProgress(Math.min(1, acc / total))
  return {
    d: toD(c.cmds),
    length: Math.ceil(c.len),
    delayMs: Math.round(t0),
    durationMs: Math.max(1, Math.round(t1) - Math.round(t0)),
  }
})

const bb = path.getBoundingBox()
const vx = Math.floor(bb.x1 - PAD), vy = Math.floor(bb.y1 - PAD)
const vw = Math.ceil(bb.x2 + PAD) - vx, vh = Math.ceil(bb.y2 + PAD) - vy
const viewBox = `${vx} ${vy} ${vw} ${vh}`

const out = `// GENERATED by scripts/generate-welcome-path.mjs - do not edit by hand.
// Run \`pnpm --filter ui-shell generate:welcome-path\` to regenerate.
//
// Glyph outlines derived from the font "Sacramento" (Copyright (c) 2012 Brian J. Bonislawsky
// DBA Astigmatic (AOETI), Reserved Font Name 'Sacramento'), licensed under the SIL Open Font
// License, Version 1.1. Source package: ${fontPkg.name}@${fontPkg.version} (license: ${fontPkg.license}),
// file files/sacramento-latin-400-normal.woff.

export interface WelcomeStroke {
  readonly d: string
  readonly length: number
  readonly delayMs: number
  readonly durationMs: number
}

export const WELCOME_PATH: {
  readonly viewBox: string
  readonly strokes: ReadonlyArray<WelcomeStroke>
} = {
  viewBox: '${viewBox}',
  strokes: [
${strokes.map(s => `    { d: '${s.d}', length: ${s.length}, delayMs: ${s.delayMs}, durationMs: ${s.durationMs} },`).join('\n')}
  ],
}
`
writeFileSync(outFile, out)
console.log(`wrote ${outFile}: ${strokes.length} strokes, viewBox ${viewBox} (${(vw / vh).toFixed(2)}:1)`)
